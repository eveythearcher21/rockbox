#!/usr/bin/env python3
"""Original 32px menu glyphs; album/playlist glyphs preserve SNARTY sprites.
SNARTY-derived sprite portions CC BY-SA4, original drawing code GPLv2+.
Spotify mark depicts the service requested by the owner; no service integration.
"""
from pathlib import Path
from PIL import Image,ImageDraw
root=Path(__file__).resolve().parents[3]
names=['music','songs','albums','artists','playlists','playing','genre','year','search','wrapped','videos','podcasts','settings','system','files','extras','radio','shortcuts','plugins','favorite','wifi','sync']
images=[]
for name in names:
 im=Image.new('1',(32,32));d=ImageDraw.Draw(im)
 def line(points):d.line(points,fill=1,width=2)
 def ellipse(box):d.ellipse(box,outline=1,width=2)
 def rect(box):d.rectangle(box,outline=1,width=2)
 if name in ('music','files'):
  line([(3,9),(3,27),(29,27),(29,9),(16,9),(13,5),(3,5),(3,9)])
  if name=='music':line([(17,22),(17,12),(24,10),(24,20)]);d.ellipse((12,20,17,24),fill=1);d.ellipse((19,18,24,22),fill=1)
 elif name=='favorite':
  d.polygon([(16,2),(20,11),(30,12),(23,19),(25,30),(16,25),(7,30),(9,19),(2,12),(12,11)],fill=1)
 elif name=='songs':
  line([(12,23),(12,8),(26,5),(26,20)]);line([(12,12),(26,9)]);d.ellipse((5,21,12,26),fill=1);d.ellipse((19,18,26,23),fill=1)
 elif name in ('albums','playlists'):
  strip=Image.open(root/'customizations/snarty-y1/.rockbox/icons/SNARTY.bmp').convert('RGB')
  source=strip.crop((0,0 if name=='albums' else 32,24,16 if name=='albums' else 48))
  for y in range(source.height):
   for x in range(source.width):
    if sum(source.getpixel((x,y)))<300:im.putpixel((x+4,y+8),1)
 elif name=='artists':
  ellipse((12,3,21,12));line([(7,29),(7,23),(10,17),(16,14),(23,17),(26,23),(26,29)])
  ellipse((3,8,9,14));line([(2,25),(2,21),(5,18)])
 elif name=='playing':
  d.polygon([(12,7),(25,16),(12,25)],fill=1);line([(4,10),(4,22)]);line([(28,10),(28,22)])
 elif name=='genre':
  line([(4,5),(18,5),(29,16),(16,29),(4,17),(4,5)]);ellipse((9,10,13,14))
 elif name=='year':
  rect((4,7,28,28));line([(4,13),(28,13)]);line([(10,3),(10,10)]);line([(22,3),(22,10)]);rect((10,18,14,22));rect((19,18,23,22))
 elif name=='search':ellipse((4,3,22,21));line([(20,20),(29,29)])
 elif name=='wrapped':
  d.ellipse((2,2,30,30),fill=1)
  for box in [(6,10,27,21),(8,15,25,24),(10,20,23,27)]:d.arc(box,205,330,fill=0,width=2)
 elif name=='videos':rect((3,5,29,27));line([(3,10),(29,10)]);line([(10,5),(10,10)]);line([(21,5),(21,10)]);d.polygon([(13,14),(22,19),(13,24)],fill=1)
 elif name=='podcasts':
  ellipse((12,3,20,11));d.ellipse((13,14,19,20),fill=1);line([(14,19),(13,29),(19,29),(18,19)])
  d.arc((6,1,26,26),130,225,fill=1,width=2);d.arc((6,1,26,26),-45,50,fill=1,width=2)
  d.arc((1,0,31,31),130,220,fill=1,width=2);d.arc((1,0,31,31),-40,50,fill=1,width=2)
 elif name in ('settings','system'):
  ellipse((8,8,24,24));ellipse((13,13,19,19))
  for p in [[(16,2),(16,8)],[(16,24),(16,30)],[(2,16),(8,16)],[(24,16),(30,16)],[(6,6),(10,10)],[(22,22),(26,26)],[(6,26),(10,22)],[(22,10),(26,6)]]:line(p)
 elif name=='extras':
  for x,y in [(4,4),(19,4),(4,19),(19,19)]:rect((x,y,x+9,y+9))
 elif name=='radio':
  rect((3,12,29,28));line([(8,12),(25,3)]);ellipse((7,17,15,25));line([(20,18),(26,18)]);line([(20,23),(26,23)])
 elif name=='wifi':
  for box in [(1,5,31,35),(6,11,26,31),(11,17,21,27)]:d.arc(box,220,320,fill=1,width=2)
  d.ellipse((14,24,18,28),fill=1)
 elif name=='sync':
  d.arc((5,5,27,27),205,350,fill=1,width=2);d.arc((5,5,27,27),25,170,fill=1,width=2)
  d.polygon([(26,5),(29,14),(20,12)],fill=1);d.polygon([(6,27),(3,18),(12,20)],fill=1)
 elif name=='shortcuts':line([(4,9),(19,9),(19,3),(29,16),(19,29),(19,23),(4,23),(4,9)])
 elif name=='plugins':
  rect((6,10,26,26));line([(12,10),(12,4),(20,4),(20,10)]);line([(6,16),(2,16),(2,22),(6,22)])
 images.append(im)
preview=Image.new('RGB',(len(images)*40,40),'#232234')
for i,im in enumerate(images):preview.paste('#a5e6ba',(i*40+4,4,i*40+36,36),im)
preview.save(root/'customizations/snarty-y1/navigation-icons.png')
text='/* Generated by make_navigation_icons.py. Original glyphs GPLv2+; SNARTY-derived album/playlist glyphs CC BY-SA4. */\n'
text+='enum snarty_icon { '+', '.join('SN_ICON_'+n.upper() for n in names)+', SN_ICON_COUNT };\n'
text+='static const uint32_t snarty_icons[SN_ICON_COUNT][32] = {\n'
for name,im in zip(names,images):
 rows=[sum(im.getpixel((x,y))<<x for x in range(32)) for y in range(32)]
 text+='/* '+name+' */ { '+', '.join('0x%08xu'%n for n in rows)+' },\n'
text+='};\n'
(root/'apps/snarty_icons.h').write_text(text)
